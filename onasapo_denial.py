"""オナサポ：我慢宣言・フル勃起矛盾いじり（onasapo からも同関数を提供）。"""
from __future__ import annotations

import hashlib
import random


def _rng(seed_key: str) -> random.Random:
    return random.Random(int(hashlib.md5(seed_key.encode("utf-8")).hexdigest(), 16))


